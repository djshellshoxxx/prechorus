#!/usr/bin/env python3
"""Generates docs/PARAMETERS.md from Source/PluginProcessor.{h,cpp} (parameter IDs, ranges, defaults, choices).

    python3 tools/gen_param_reference.py            # rewrite docs/PARAMETERS.md
    python3 tools/gen_param_reference.py --check    # exit 1 if the file is out of date (used by CI)
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
hdr = (root / "Source/PluginProcessor.h").read_text()
src = (root / "Source/PluginProcessor.cpp").read_text()

ids = {}
ns = hdr[hdr.index("namespace IDs"):hdr.index("inline float tensionCurve")]
for m in re.finditer(r'(\w+)\s*=\s*"([^"]+)"', ns):
    ids[m.group(1)] = m.group(2)

layout = src[src.index("PreChorusProcessor::createLayout()"):src.index("bool PreChorusProcessor::isBusesLayoutSupported")]
rows = []
for m in re.finditer(r'std::make_unique<juce::AudioParameter(Choice|Float|Int|Bool)>\s*\((.*?)\)\);', layout, re.S):
    kind, body = m.group(1), m.group(2)
    idm = re.match(r'IDs::(\w+),\s*"([^"]+)",\s*(.*)', body, re.S)
    key, name, rest = idm.group(1), idm.group(2), idm.group(3).strip()
    pid = ids[key]
    if kind == "Choice":
        cm = re.match(r'juce::StringArray\s*\{(.*?)\},\s*(\d+)', rest, re.S)
        choices = re.findall(r'"([^"]*)"', cm.group(1))
        default = choices[int(cm.group(2))]
        rows.append((pid, name, "Choice", " / ".join(f"{i}={c}" for i, c in enumerate(choices)), default))
    elif kind == "Float":
        rm = re.match(r'juce::NormalisableRange<float>\s*\(([^)]*)\),\s*([-\d.]+)f', rest)
        parts = [p.strip().rstrip("f") for p in rm.group(1).split(",")]
        rng = f"{parts[0]} .. {parts[1]} (step {parts[2]}" + (f", skew {parts[3]}" if len(parts) > 3 else "") + ")"
        rows.append((pid, name, "Float", rng, rm.group(2)))
    elif kind == "Int":
        im = re.match(r'(-?\d+),\s*(\d+),\s*(-?\d+)', rest)
        rows.append((pid, name, "Int", f"{im.group(1)} .. {im.group(2)}", im.group(3)))
    else:
        rows.append((pid, name, "Bool", "off / on", "on" if rest.strip() == "true" else "off"))

out = ["# PreChorus parameter reference", "",
       "Generated by `tools/gen_param_reference.py` from the parameter layout in `Source/PluginProcessor.cpp`. Do not edit by hand.",
       "Parameter IDs are stable: an ID is never reused for a different meaning, and new parameters are only ever appended.", "",
       f"{len(rows)} automatable parameters.", "",
       "| ID | Name | Type | Range / choices | Default |", "|---|---|---|---|---|"]
for pid, name, kind, rng, default in rows:
    out.append(f"| `{pid}` | {name} | {kind} | {rng} | {default} |")
out += ["", "Choice values are stored as their zero-based index. Sound-design parameters (everything except the source, capture, mix level,",
        "trim, target-source and morph controls) are covered by presets, A/B snapshots, undo and the randomizer.", ""]
text = "\n".join(out)

target = root / "docs/PARAMETERS.md"
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != text:
        print("docs/PARAMETERS.md is out of date: run python3 tools/gen_param_reference.py"); sys.exit(1)
    print("docs/PARAMETERS.md is up to date"); sys.exit(0)
target.write_text(text)
print(f"wrote {target} ({len(rows)} parameters)")
